use std::collections::BTreeMap;

const MIXIN: [usize; 64] = [
    46, 47, 18, 2, 53, 8, 23, 32, 15, 50, 10, 31, 58, 3, 45, 35, 27, 43, 5, 49, 33, 9, 42, 19, 29,
    28, 14, 39, 12, 38, 41, 13, 37, 48, 7, 16, 24, 55, 40, 61, 26, 17, 0, 1, 60, 51, 30, 4, 22, 25,
    54, 21, 56, 59, 6, 63, 57, 62, 11, 36, 20, 34, 44, 52,
];

pub fn mixin_key(img_key: &str, sub_key: &str) -> String {
    let source = format!("{img_key}{sub_key}");
    MIXIN
        .into_iter()
        .filter_map(|index| source.as_bytes().get(index).copied())
        .take(32)
        .map(char::from)
        .collect()
}

// encodeURIComponent 保留 -_.!~*'()；WBI 值先剔除 !'()*，不可把空白編碼為 +。
pub fn encode_component(value: &str) -> String {
    let mut encoded = String::new();
    for byte in value.bytes() {
        if byte.is_ascii_alphanumeric() || b"-_.!~*'()".contains(&byte) {
            encoded.push(byte as char);
        } else {
            use std::fmt::Write;
            write!(encoded, "%{byte:02X}").expect("writing String");
        }
    }
    encoded
}

pub fn sign(
    params: &BTreeMap<String, String>,
    img_key: &str,
    sub_key: &str,
    timestamp_sec: u64,
) -> String {
    let mut params = params.clone();
    params.remove("w_rid");
    params.insert("wts".into(), timestamp_sec.to_string());
    let query = params
        .iter()
        .map(|(key, value)| {
            let cleaned: String = value.chars().filter(|c| !"!'()*".contains(*c)).collect();
            format!("{}={}", encode_component(key), encode_component(&cleaned))
        })
        .collect::<Vec<_>>()
        .join("&");
    let hash = md5::compute(format!("{query}{}", mixin_key(img_key, sub_key)));
    format!("{query}&w_rid={hash:x}")
}

